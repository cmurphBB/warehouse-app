-- Server-only config (cron token etc.). Never exposed.
create table inventory.app_config (
  key text primary key,
  value text not null
);
insert into inventory.app_config(key, value) values ('cron_token', encode(gen_random_bytes(24), 'hex'));

-- Lock everything: only the server (postgres role via the edge function) touches these tables.
do $$ declare t text; begin
  for t in select tablename from pg_tables where schemaname = 'inventory' loop
    execute format('alter table inventory.%I enable row level security', t);
    execute format('revoke all on inventory.%I from anon, authenticated', t);
  end loop;
end $$;

