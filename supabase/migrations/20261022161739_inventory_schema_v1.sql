-- Blue Bear Inventory — Postgres port of the Muse SQLite schema (drizzle/0001–0009),
-- plus water-heater / ServiceTitan columns on equipment and the email claim column.
-- Lives in its own `inventory` schema inside the blue-bear-warehouse project.
create schema if not exists inventory;
revoke all on schema inventory from anon, authenticated;

create table inventory.entries (
  id integer generated by default as identity primary key,
  text text not null,
  created_at timestamptz not null default now()
);

create table inventory.parts (
  id integer generated by default as identity primary key,
  name text not null,
  sku text not null default '',
  category text not null default 'General',
  department text not null default 'Other',
  unit text not null default 'ea',
  avg_cost_cents integer not null default 0,
  last_cost_cents integer not null default 0,
  price_count integer not null default 0,
  last_vendor text not null default '',
  last_priced_at text not null default '',
  created_at timestamptz not null default now()
);

create table inventory.locations (
  id integer generated by default as identity primary key,
  name text not null,
  kind text not null default 'warehouse' check (kind in ('warehouse','truck')),
  assigned_to text not null default '',
  created_at timestamptz not null default now()
);

create table inventory.stock_levels (
  id integer generated by default as identity primary key,
  part_id integer not null,
  location_id integer not null,
  quantity integer not null default 0,
  min_qty integer not null default 2
);
create index on inventory.stock_levels(part_id);
create index on inventory.stock_levels(location_id);

create table inventory.orders (
  id integer generated by default as identity primary key,
  vendor text not null,
  po_number text not null default '',
  status text not null default 'ordered',
  eta text not null default '',
  notes text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table inventory.order_lines (
  id integer generated by default as identity primary key,
  order_id integer not null,
  part_id integer,
  part_name text not null,
  sku text not null default '',
  qty integer not null default 1,
  received_qty integer not null default 0,
  unit_cost_cents integer not null default 0
);
create index on inventory.order_lines(order_id);

create table inventory.staging_jobs (
  id integer generated by default as identity primary key,
