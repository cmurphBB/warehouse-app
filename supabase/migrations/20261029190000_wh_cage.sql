-- Blue Bear water heater CAGE (process rolled out 2026-10-27): Blue Bear-OWNED
-- units held at par in a locked cage, signed out FIFO with a signature, each
-- sign-out reordered on that job's PO, counted every Tuesday.
-- Consigned water heaters (supply-house owned) keep the existing Pull flow;
-- cage code applies only to rows with wh_type set.

-- The six cage types and their pars.
create table inventory.wh_types (
  key text primary key,
  label text not null,
  fuel text not null default '',
  gallons integer not null default 0,
  par integer not null default 0,
  sort integer not null default 0
);

insert into inventory.wh_types (key, label, fuel, gallons, par, sort) values
  ('40e',  '40 gal Electric',          'Electric', 40, 2, 1),
  ('40g',  '40 gal Gas',               'Gas',      40, 2, 2),
  ('50e',  '50 gal Electric',          'Electric', 50, 2, 3),
  ('50g',  '50 gal Gas',               'Gas',      50, 2, 4),
  ('50pv', '50 gal Power Vent',        'Gas',      50, 1, 5),
  ('tl199','State Tankless 199k BTU',  'Gas',       0, 1, 6);

-- Cage fields on equipment. received_at is the FIFO clock (backfilled from
-- created_at); the released_* / tech / signature / after_hours fields hold the
-- unit's LATEST sign-out — the per-event record lives on wh_reorders.
alter table inventory.equipment
  add column wh_type text references inventory.wh_types(key),
  add column received_at timestamptz,
  add column po_number text not null default '',
  add column released_by text not null default '',
  add column released_by_name text not null default '',
  add column tech_name text not null default '',
  add column signature_blob_key text not null default '',
  add column after_hours integer not null default 0,
  add column fifo_override_reason text not null default '';

update inventory.equipment set received_at = created_at where received_at is null;

-- One row per sign-out. It doubles as the reorder tracker for that job's PO:
-- open → ordered (PO #) → received; cancelled when the unit comes back unused.
create table inventory.wh_reorders (
  id integer generated by default as identity primary key,
  wh_type text not null references inventory.wh_types(key),
  equipment_id integer not null,
  serial_number text not null default '',
  job_number text not null default '',
  status text not null default 'open' check (status in ('open','ordered','received','cancelled')),
  po_number text not null default '',
  tech_name text not null default '',
  released_by text not null default '',
  released_by_name text not null default '',
  signature_blob_key text not null default '',
  after_hours integer not null default 0,
  fifo_override_reason text not null default '',
  created_at timestamptz not null default now(),
  ordered_at timestamptz,
  ordered_by text not null default '',
  received_at timestamptz,
  received_by text not null default '',
  received_equipment_id integer
);

-- Tuesday counts: a session plus one line per serial scanned / missing / unexpected.
create table inventory.wh_counts (
  id integer generated by default as identity primary key,
  started_by text not null default '',
  started_at timestamptz not null default now(),
  finished_by text not null default '',
  finished_at timestamptz,
  expected integer not null default 0,
  scanned integer not null default 0,
  missing integer not null default 0,
  unexpected integer not null default 0
);

create table inventory.wh_count_lines (
  id integer generated by default as identity primary key,
  count_id integer not null references inventory.wh_counts(id),
  equipment_id integer,
  serial_number text not null default '',
  wh_type text not null default '',
  result text not null default 'scanned' check (result in ('scanned','missing','unexpected')),
  created_at timestamptz not null default now()
);

-- Locked to the server, like every other inventory table (PGlite in tests
